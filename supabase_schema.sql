-- Run this in Supabase Dashboard -> SQL Editor.
-- This public demo uses the service-role key only on the Streamlit server.
-- Do NOT put the service-role key in client-side code or GitHub.

create table if not exists public.generation_history (
    id bigint generated by default as identity primary key,
    session_id uuid not null,
    video_id text not null,
    title text not null,
    source_url text not null,
    mode text not null check (mode in ('diagrams', 'text', 'watch')),
    language text not null,
    notes_markdown text not null,
    status text not null default 'completed'
        check (status in ('completed', 'partial')),
    created_at timestamptz not null default now()
);

create index if not exists generation_history_session_created_idx
    on public.generation_history (session_id, created_at desc);

alter table public.generation_history enable row level security;

-- No anon/authenticated policies are intentionally created. The app accesses this
-- table server-side using SUPABASE_SERVICE_ROLE_KEY, which bypasses RLS. Keep that
-- key exclusively in Streamlit secrets. The app filters every history query by the
-- server-side Streamlit session UUID.
